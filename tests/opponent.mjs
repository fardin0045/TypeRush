import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true,channel:'chrome'});
const page=await browser.newPage();
await page.goto('http://127.0.0.1:5177');
await page.getByRole('button',{name:'Custom race',exact:true}).click();
await page.getByLabel('Difficulty',{exact:true}).selectOption('Expert');
await page.getByLabel('Passage length').selectOption('Short');
await page.getByRole('button',{name:'Start race',exact:true}).click();
await page.getByRole('dialog',{name:'Race results'}).waitFor({timeout:60000});
assert.match(await page.locator('.dialog>p').first().innerText(),/You placed 4th/);
assert.equal(await page.locator('.results-table tbody tr').count(),4);
const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('typerush.v1')));
assert.equal(saved.losses,1);
await page.getByRole('button',{name:'Race again',exact:true}).last().click();
await page.waitForFunction(()=>!document.querySelector('input[aria-label="Type the passage here"]').disabled);
assert.equal(await page.locator('.lane-progress').first().innerText(),'0%');
console.log('PASS: AI finishes independently, all four actual standings, loss saved, Race Again resets.');
await browser.close();
