import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true,channel:'chrome'});
const page=await browser.newPage({viewport:{width:1536,height:864}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:5177');
await page.getByRole('button',{name:'Start race',exact:true}).waitFor();
async function visibleScreen(){assert.ok(await page.evaluate(()=>document.documentElement.scrollHeight<=innerHeight&&document.documentElement.scrollWidth<=innerWidth));for(const selector of ['.passage','.input-row input','.typing-bottom','.road-scene']){const b=await page.locator(selector).boundingBox();assert.ok(b&&b.y>=0&&b.y+b.height<=page.viewportSize().height,selector+' must fit viewport');}}
await visibleScreen();
await page.screenshot({path:'tests/immersive-desktop.png'});
await page.getByLabel('Difficulty',{exact:true}).selectOption('Easy');
const passage=await page.getByLabel('Typing passage',{exact:true}).innerText();
await page.getByRole('button',{name:'Start race',exact:true}).click();
await page.waitForFunction(()=>!document.querySelector('.input-row input').disabled);
await page.getByRole('textbox').pressSequentially(passage,{delay:35});
await page.getByRole('dialog',{name:'Race results'}).waitFor();
assert.match(await page.locator('.dialog').innerText(),/First across the line/);
await page.reload();
await page.setViewportSize({width:390,height:844});
await visibleScreen();
await page.screenshot({path:'tests/immersive-mobile.png'});
await page.getByRole('button',{name:'Start race',exact:true}).click();
await page.waitForFunction(()=>!document.querySelector('.input-row input').disabled);
const text=await page.getByLabel('Typing passage',{exact:true}).innerText();
await page.getByRole('textbox').pressSequentially(text.slice(0,100),{delay:20});
assert.ok(await page.evaluate(()=>{const p=document.querySelector('.passage'),c=p.querySelector('.current');const a=p.getBoundingClientRect(),b=c.getBoundingClientRect();return b.top>=a.top&&b.bottom<=a.bottom;}),'active character is visible after typing');
await page.setViewportSize({width:844,height:390});
await visibleScreen();
assert.deepEqual(errors,[]);
console.log('PASS: viewport-filling desktop/mobile/landscape, visible typing controls, full race win, automatic passage scroll, no console errors.');
await browser.close();
