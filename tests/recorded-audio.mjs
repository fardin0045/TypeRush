import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true,channel:'chrome'});
const page=await browser.newPage();
const errors=[],samples=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('response',r=>{if(r.url().endsWith('.wav'))samples.push(r.status());});
await page.addInitScript(()=>{window.recordedPlays=[];const start=AudioBufferSourceNode.prototype.start;AudioBufferSourceNode.prototype.start=function(...args){window.recordedPlays.push({duration:this.buffer?.duration,rate:this.playbackRate.value});return start.apply(this,args);};});
await page.goto('http://127.0.0.1:5177');
assert.equal(await page.evaluate(()=>window.recordedPlays.length),0);
await page.getByRole('button',{name:'Enable sound',exact:true}).click();
const passage=await page.getByLabel('Typing passage',{exact:true}).innerText();
await page.getByRole('button',{name:'Start race',exact:true}).click();
await page.waitForFunction(()=>!document.querySelector('.input-row input').disabled);
await page.keyboard.type(passage.slice(0,12),{delay:35});
const played=await page.evaluate(()=>window.recordedPlays);
assert.equal(played.length,12);
assert.ok(played.every(p=>p.duration>.1&&p.duration<.12));
assert.equal(samples.length,8);assert.ok(samples.every(s=>s===200));
await page.getByRole('button',{name:'Mute sound'}).click();
await page.getByLabel('Typing passage',{exact:true}).click();
await page.keyboard.type(passage.slice(12,20),{delay:25});
assert.equal(await page.evaluate(()=>window.recordedPlays.length),12);
assert.deepEqual(errors,[]);
console.log('PASS: eight real WAV assets loaded, twelve decoded sample playbacks, no audio before enabling, mute respected, no browser errors.');
await browser.close();
