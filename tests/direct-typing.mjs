import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true,channel:'chrome'});
const page=await browser.newPage({viewport:{width:1536,height:864}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.addInitScript(()=>{window.clicks=0;const original=AudioContext.prototype.createBufferSource;AudioContext.prototype.createBufferSource=function(){window.clicks++;return original.call(this);};});
await page.goto('http://127.0.0.1:5177');
await page.getByRole('button',{name:'Start race',exact:true}).waitFor();
assert.ok((await page.locator('.typing-panel').boundingBox()).height<190);
assert.ok((await page.locator('.track').boundingBox()).height>500);
assert.ok((await page.locator('.input-row').boundingBox()).height<=1);
await page.screenshot({path:'tests/direct-typing-desktop.png'});
await page.getByRole('button',{name:'Enable sound',exact:true}).click();
const passage=await page.getByLabel('Typing passage',{exact:true}).innerText();
await page.getByRole('button',{name:'Start race',exact:true}).click();
await page.waitForFunction(()=>!document.querySelector('.input-row input').disabled);
await page.keyboard.type(passage.slice(0,8),{delay:45});
assert.equal(await page.locator('.passage .correct').count(),8);
assert.ok(await page.evaluate(()=>window.clicks>=8));
await page.keyboard.type('~');
await page.getByText('Press Backspace to correct the highlighted character.').waitFor();
await page.keyboard.press('Backspace');
await page.getByRole('button',{name:'Mute sound'}).click();
const before=await page.evaluate(()=>window.clicks);
await page.getByLabel('Typing passage',{exact:true}).click();
await page.keyboard.type(passage.slice(8),{delay:25});
await page.getByRole('dialog',{name:'Race results'}).waitFor();
assert.equal(await page.evaluate(()=>window.clicks),before);
await page.reload();await page.setViewportSize({width:390,height:844});
assert.ok((await page.locator('.typing-panel').boundingBox()).height<170);
await page.screenshot({path:'tests/direct-typing-mobile.png'});
await page.getByRole('button',{name:'Start race',exact:true}).click();
await page.waitForFunction(()=>!document.querySelector('.input-row input').disabled);
await page.getByLabel('Typing passage',{exact:true}).click();
assert.ok(await page.evaluate(()=>document.activeElement===document.querySelector('.input-row input')));
assert.deepEqual(errors,[]);
console.log('PASS: compact panel, taller road, direct typing, correction, complete race, mechanical click playback/mute, mobile tap focus.');
await browser.close();
